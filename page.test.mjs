import assert from 'node:assert/strict';
import { test } from 'node:test';
import { pageFor, question, request } from './page.mjs';

const item = { number: 982, title: 'Guarded file nodes 3', html_url: 'https://github.com/o/r/issues/982', labels: [{ name: 'swarm/needs-human' }] };
const label = { name: 'swarm/needs-human' };

test('the question is the latest comment, without markers or the trailer', () => {
  const comments = [{ body: 'earlier' }, { body: '**Needs a person:** VHS loaders, a or b?\n\n<!-- agent: claude-2 -->\n\n---\n_Generated by Claude Code_' }];
  assert.equal(question(comments), 'Needs a person: VHS loaders, a or b?');
  assert.equal(question([]), '');
  assert.equal(question([{ body: 'x'.repeat(900) }]).length, 400);
});

test('labelling pages urgently, clearing pages quietly, anything else does not page', () => {
  const page = pageFor({ action: 'labeled', label, issue: item }, { open: 2, asked: 'a or b?' });
  assert.deepEqual([page.state, page.priority, page.open, page.number], ['waiting', 5, 2, 982]);
  assert.match(page.title, /^Couchy needs you: #982 Guarded/);
  assert.equal(page.text, 'a or b?\n\n2 waiting on you.');
  assert.match(pageFor({ action: 'labeled', label, pull_request: item }, { open: 1 }).text, /^PR #982 is waiting/);

  assert.deepEqual(pageFor({ action: 'unlabeled', label, issue: item }, { open: 0 }).text, 'Nothing is waiting on you.');
  assert.equal(pageFor({ action: 'closed', issue: item }, { open: 1 }).state, 'cleared');
  assert.equal(pageFor({ action: 'closed', issue: { ...item, labels: [] } }, { open: 1 }), null);
  assert.equal(pageFor({ action: 'labeled', label: { name: 'area/api' }, issue: item }, { open: 1 }), null);
  assert.equal(pageFor({}, { open: 3 }).state, 'test');
});

test('ntfy gets the text as the body and the rest in the query; json gets one object', () => {
  const page = pageFor({ action: 'labeled', label, issue: { ...item, title: 'Settings › Keys' } }, { open: 1, asked: 'which?' });
  const ntfy = request(page, { url: 'https://ntfy.example/couchy-needs-me', token: 't' });
  const to = new URL(ntfy.url);
  assert.equal(to.searchParams.get('title'), 'Couchy needs you: #982 Settings › Keys');
  assert.deepEqual([to.searchParams.get('priority'), to.searchParams.get('click')], ['5', item.html_url]);
  assert.equal(ntfy.init.body, 'which?\n\n1 waiting on you.');
  assert.equal(ntfy.init.headers.Authorization, 'Bearer t');
  const json = request(page, { url: 'https://hook.example/x', format: 'json' });
  assert.deepEqual(JSON.parse(json.init.body).open, 1);
  assert.equal(json.url, 'https://hook.example/x');
});
